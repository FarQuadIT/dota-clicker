/**
 * Унифицированные состояния для игровых сущностей и игрового процесса
 * Используются для управления логикой и анимациями в игре
 */

/**
 * Состояния игровой сущности (герой, крип и т.д.)
 */
export enum EntityState {
  /** Стоит на месте, не двигается */
  IDLE = 'idle',
  /** Движется по игровому миру */
  MOVING = 'moving',
  /** Выполняет атаку */
  ATTACKING = 'attacking',
  /** Проигрывает анимацию смерти */
  DYING = 'dying',
  /** Анимация смерти завершена, готов к удалению */
  DEAD = 'dead',
}

/**
 * Состояния игрового процесса
 */
export enum GameState {
  /** Идет загрузка ресурсов и инициализация */
  LOADING = 'loading',
  /** Игра активна: герой бежит, крипы движутся */
  RUNNING = 'running',
  /** Бой: оба атакуют, мир остановлен */
  FIGHTING = 'fighting',
  /** Игра на паузе (например, свернута или открыт overlay) */
  PAUSED = 'paused',
  /** Ожидание спавна нового крипа */
  WAITING = 'waiting',
} 