/**
 * Конфигурация экрана и размеров по умолчанию
 */
interface ScreenConfig {
  /** Ширина экрана по умолчанию (px) */
  defaultWidth: number;
  
  /** Высота экрана по умолчанию (px) */
  defaultHeight: number;
  
  /** Соотношение сторон по умолчанию */
  aspectRatio: number;
  
  /** Базовое разрешение для расчета масштабирования */
  baseResolution: number;
}

/**
 * Конфигурация героя (позиции, масштаб, анимации)
 */
interface HeroConfig {
  /** Конфигурация позиционирования героя */
  position: {
    /** Позиция по X относительно ширины экрана (0-1) */
    x: number;
    
    /** Позиция по Y относительно высоты экрана (0-1) */
    y: number;
  };
  
  /** Конфигурация масштабирования */
  scale: {
    /** Базовый масштаб героя */
    base: number;
    
    /** Масштаб для GamePage (увеличенный) */
    gamePage: number;
    
    /** Минимальный допустимый масштаб */
    min: number;
    
    /** Максимальный допустимый масштаб */
    max: number;
  };
  
  /** Конфигурация анимаций героя */
  animations: {
    /** Частота кадров для анимации idle */
    idleFrameRate: number;
    
    /** Частота кадров для анимации run */
    runFrameRate: number;
    
    /** Частота кадров для анимации attack */
    attackFrameRate: number;
    
    /** Кадр нанесения урона в анимации атаки (начиная с 0) */
    damageFrame: number;
  };
}

/**
 * Конфигурация крипов (позиции, скоростей, смещений)
 */
interface CreepConfig {
  /** Конфигурация спавна крипов */
  spawn: {
    /** Начальная позиция X (за правым краем экрана) */
    startX: number;
    
    /** Позиция Y (уровень земли) */
    positionY: number;
    
    /** Дополнительное смещение от края экрана */
    spawnOffset: number;
  };
  
  /** Конфигурация движения */
  movement: {
    /** Базовая скорость движения крипа (пикселей/тик) */
    baseSpeed: number;
    
    /** Скорость движения фона (синхронизированная) */
    backgroundSpeed: number;
    
    /** Множитель скорости крипа (отдельно от фона) */
    speedMultiplier: number;
  };
  
  /** Конфигурация анимации смерти */
  death: {
    /** Смещение по X при переходе в анимацию смерти */
    offsetX: number;
    
    /** Смещение по Y при переходе в анимацию смерти */
    offsetY: number;
    
    /** Максимальная длительность анимации смерти (мс) */
    maxDuration: number;
  };
  
  /** Конфигурация анимаций */
  animations: {
    /** Скорость воспроизведения анимаций */
    speed: number;
  };
  
  /** Масштабирование крипов */
  scale: {
    /** Базовый масштаб крипа */
    base: number;
  };
}

/**
 * Конфигурация игровой механики (коллизии, таймеры, скорости)
 */
interface GameMechanicsConfig {
  /** Конфигурация боевой системы */
  combat: {
    /** Время паузы после смерти крипа перед спавном нового (мс) */
    spawnDelay: number;
    
    /** Стоимость атаки в единицах энергии */
    attackEnergyCost: number;
  };
  
  /** Конфигурация движения */
  movement: {
    /** Базовая скорость движения в игре */
    baseSpeed: number;
  };
  
  /** Конфигурация коллизий */
  collision: {
    /** Зона коллизии между героем и крипом (относительно экрана) */
    detectionZone: number;
  };
}

/**
 * Конфигурация фона и визуальных эффектов
 */
interface BackgroundConfig {
  /** Конфигурация прокрутки фона */
  scroll: {
    /** Скорость прокрутки фона (пикселей/тик) */
    speed: number;
    
    /** Множитель ширины для TilingSprite */
    widthMultiplier: number;
    
    /** Общий коэффициент скорости движения мира */
    speedMultiplier: number;
    
    /** Соотношение скорости крипа к фону (1.0 = одинаковые) */
    creepSyncRatio: number;
  };
  
  /** Fallback цвет фона при ошибке загрузки */
  fallback: {
    /** Цвет фона (hex) */
    color: number;
  };
}

/**
 * Основной интерфейс конфигурации игры
 */
export interface GameConfig {
  /** Настройки экрана и размеров */
  SCREEN: ScreenConfig;
  
  /** Настройки героя */
  HERO: HeroConfig;
  
  /** Настройки крипов */
  CREEP: CreepConfig;
  
  /** Настройки игровой механики */
  GAME_MECHANICS: GameMechanicsConfig;
  
  /** Настройки фона */
  BACKGROUND: BackgroundConfig;
}

